use crate::config::schema::*;
use anyhow::Result;

/// Render /etc/wireguard/wg0.conf from config.
pub fn render(config: &Config) -> Result<String> {
    let vpn = match &config.vpn {
        Some(v) => v,
        None => return Ok("# VPN not configured\n".into()),
    };

    let wg = match &vpn.wireguard {
        Some(w) => w,
        None => return Ok("# WireGuard not configured\n".into()),
    };

    if !wg.enabled {
        return Ok("# WireGuard disabled\n".into());
    }

    let mut out = String::with_capacity(1024);

    out.push_str("# AUTO-GENERATED by routerd — DO NOT EDIT MANUALLY\n\n");

    // Interface section
    out.push_str("[Interface]\n");
    out.push_str(&format!("PrivateKey = {}\n", wg.private_key));
    out.push_str(&format!("Address = {}\n", wg.address));
    out.push_str(&format!("ListenPort = {}\n", wg.listen_port));
    out.push_str("SaveConfig = false\n");
    out.push('\n');

    // Peer sections
    for peer in &wg.peers {
        if !peer.enabled {
            continue;
        }

        out.push_str(&format!("# Peer: {}\n", peer.name));
        out.push_str("[Peer]\n");
        out.push_str(&format!("PublicKey = {}\n", peer.public_key));

        if !peer.allowed_ips.is_empty() {
            out.push_str(&format!("AllowedIPs = {}\n", peer.allowed_ips.join(", ")));
        }

        if let Some(endpoint) = &peer.endpoint {
            out.push_str(&format!("Endpoint = {}\n", endpoint));
        }

        out.push_str("PersistentKeepalive = 25\n");
        out.push('\n');
    }

    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_render_enabled() {
        let mut config = Config::default();
        config.vpn = Some(Vpn {
            wireguard: Some(WireguardConfig {
                enabled: true,
                listen_port: 51820,
                private_key: "AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA=".into(),
                address: "10.10.0.1/24".into(),
                peers: vec![
                    WireguardPeer {
                        name: "laptop".into(),
                        public_key: "BBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBB=".into(),
                        allowed_ips: vec!["10.10.0.2/32".into()],
                        endpoint: None,
                        enabled: true,
                    },
                    WireguardPeer {
                        name: "phone".into(),
                        public_key: "CCCCCCCCCCCCCCCCCCCCCCCCCCCCCCCCCCCCCCCCCCC=".into(),
                        allowed_ips: vec!["10.10.0.3/32".into()],
                        endpoint: Some("vpn.example.com:51820".into()),
                        enabled: true,
                    },
                    WireguardPeer {
                        name: "disabled-peer".into(),
                        public_key: "DDDDDDDDDDDDDDDDDDDDDDDDDDDDDDDDDDDDDDDDD=".into(),
                        allowed_ips: vec!["10.10.0.4/32".into()],
                        endpoint: None,
                        enabled: false,
                    },
                ],
            }),
        });

        let output = render(&config).unwrap();
        assert!(output.contains("[Interface]"));
        assert!(output.contains("ListenPort = 51820"));
        assert!(output.contains("Address = 10.10.0.1/24"));
        assert!(output.contains("# Peer: laptop"));
        assert!(output.contains("PublicKey = BBBBB"));
        assert!(output.contains("AllowedIPs = 10.10.0.2/32"));
        assert!(output.contains("# Peer: phone"));
        assert!(output.contains("Endpoint = vpn.example.com:51820"));
        assert!(!output.contains("# Peer: disabled-peer"));
    }

    #[test]
    fn test_render_disabled() {
        let mut config = Config::default();
        config.vpn = Some(Vpn {
            wireguard: Some(WireguardConfig {
                enabled: false,
                ..Default::default()
            }),
        });

        let output = render(&config).unwrap();
        assert!(output.contains("disabled"));
    }

    #[test]
    fn test_render_no_vpn() {
        let config = Config::default();
        let output = render(&config).unwrap();
        assert!(output.contains("not configured"));
    }
}
