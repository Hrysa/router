use crate::config::schema::*;
use anyhow::Result;

/// Render nftables.conf from config.
pub fn render(config: &Config) -> Result<String> {
    let mut out = String::with_capacity(4096);

    out.push_str("#!/usr/sbin/nft -f\n");
    out.push_str("# AUTO-GENERATED by routerd — DO NOT EDIT MANUALLY\n\n");
    out.push_str("flush ruleset\n\n");

    // Check if firewall has any user-defined rules
    let has_rules = !config.firewall.rules.input.is_empty()
        || !config.firewall.rules.forward.is_empty()
        || !config.firewall.nat.masquerade.is_empty()
        || !config.firewall.nat.port_forward.is_empty()
        || !config.firewall.blackhole.is_empty()
        || !config.firewall.sets.is_empty()
        || has_tproxy_rules(config);

    if has_rules {
        // Full ruleset
        render_filter_table(config, &mut out);

        if needs_nat(config) {
            render_nat_table(config, &mut out);
        }

        if has_tproxy_rules(config) {
            render_tproxy_table(config, &mut out);
        }

        if !config.firewall.blackhole.is_empty() {
            render_blackhole(config, &mut out);
        }
    } else {
        // Empty init: accept all traffic to avoid lockout
        out.push_str("# Empty ruleset — all traffic accepted (init mode)\n");
        out.push_str("# Configure firewall rules via routerd API or WebUI\n\n");
        out.push_str("table inet filter {\n");
        out.push_str("    chain input {\n");
        out.push_str("        type filter hook input priority 0; policy accept;\n");
        out.push_str("    }\n");
        out.push_str("    chain forward {\n");
        out.push_str("        type filter hook forward priority 0; policy accept;\n");
        out.push_str("    }\n");
        out.push_str("    chain output {\n");
        out.push_str("        type filter hook output priority 0; policy accept;\n");
        out.push_str("    }\n");
        out.push_str("}\n");
    }

    Ok(out)
}

/// Render user-defined nftables sets inside the filter table.
fn render_nft_sets(config: &Config, out: &mut String) {
    for set in &config.firewall.sets {
        out.push_str(&format!("    set {} {{\n", set.name));
        out.push_str(&format!("        type {}\n", set.set_type));
        if set.interval {
            out.push_str("        flags interval\n");
        }
        if !set.elements.is_empty() {
            out.push_str("        elements = {\n");
            let elements: Vec<&str> = set.elements.lines()
                .map(|l| l.trim())
                .filter(|l| !l.is_empty())
                .collect();
            for (i, elem) in elements.iter().enumerate() {
                if i > 0 {
                    out.push_str(",\n");
                }
                out.push_str(&format!("            {}", elem));
            }
            out.push_str("\n        }\n");
        }
        if let Some(comment) = &set.comment {
            out.push_str(&format!("        # {}\n", comment));
        }
        out.push_str("    }\n\n");
    }
}

fn render_filter_table(config: &Config, out: &mut String) {
    out.push_str("table inet filter {\n");

    // User-defined sets
    render_nft_sets(config, out);

    // Input chain
    out.push_str("    chain input {\n");
    out.push_str(&format!(
        "        type filter hook input priority 0; policy {};\n",
        config.firewall.default_policy.input
    ));

    // User-defined input rules (skip tproxy — they live in their own table)
    for rule in config.firewall.rules.input.iter().filter(|r| r.enabled && r.action != Action::Tproxy) {
        render_rule(rule, "        ", out);
    }

    out.push_str("    }\n\n");

    // Forward chain
    out.push_str("    chain forward {\n");
    out.push_str(&format!(
        "        type filter hook forward priority 0; policy {};\n",
        config.firewall.default_policy.forward
    ));

    for rule in config.firewall.rules.forward.iter().filter(|r| r.enabled && r.action != Action::Tproxy) {
        render_rule(rule, "        ", out);
    }

    out.push_str("    }\n\n");

    // Output chain (usually accept)
    out.push_str("    chain output {\n");
    out.push_str(&format!(
        "        type filter hook output priority 0; policy {};\n",
        config.firewall.default_policy.output
    ));
    out.push_str("    }\n");

    out.push_str("}\n\n");
}

fn render_rule(rule: &FirewallRule, indent: &str, out: &mut String) {
    out.push_str(indent);

    // Ingress interface match
    if !rule.interfaces.is_empty() {
        if rule.interfaces.len() == 1 {
            out.push_str(&format!("iifname \"{}\" ", rule.interfaces[0]));
        } else {
            out.push_str("iifname { ");
            for (i, iface) in rule.interfaces.iter().enumerate() {
                if i > 0 {
                    out.push_str(", ");
                }
                out.push_str(&format!("\"{}\"", iface));
            }
            out.push_str(" } ");
        }
    }
    if let Some(oif) = &rule.oif {
        out.push_str(&format!("oifname \"{}\" ", oif));
    }

    // Source/dest address
    if let Some(saddr) = &rule.saddr {
        out.push_str(&format!("ip saddr {} ", saddr));
    }
    if let Some(daddr) = &rule.daddr {
        if daddr == "@local" {
            out.push_str("fib daddr type local ");
        } else {
            out.push_str(&format!("ip daddr {} ", daddr));
        }
    }

    // Protocol
    if let Some(proto) = &rule.proto {
        out.push_str(&format!("{} ", proto));
    }

    // Destination port
    if let Some(dport) = &rule.dport {
        out.push_str("dport ");
        render_port_spec(dport, out);
        out.push(' ');
    }

    // Source port
    if let Some(sport) = &rule.sport {
        out.push_str("sport ");
        render_port_spec(sport, out);
        out.push(' ');
    }

    // Connection state
    if let Some(states) = &rule.state {
        if !states.is_empty() {
            out.push_str(&format!("ct state {} ", states.join(",")));
        }
    }

    // Rate limit
    if let Some(rate) = &rule.rate {
        out.push_str(&format!("limit rate {} ", rate));
    }

    // Logging
    if rule.log {
        if let Some(prefix) = &rule.log_prefix {
            out.push_str(&format!("counter log prefix \"{}: \" ", prefix));
        } else {
            out.push_str("counter log ");
        }
    } else if rule.counter {
        // Standalone counter (counter is already included in log lines above)
        out.push_str("counter ");
    }

    // Action
    match rule.action {
        Action::Accept => out.push_str("accept"),
        Action::Drop => out.push_str("drop"),
        Action::Reject => out.push_str("reject"),
        Action::Tproxy => {} // rendered in the tproxy table, not here
    }

    // nftables comment keyword (preserved in JSON output for stats matching)
    if !rule.comment.is_empty() {
        out.push_str(&format!(" comment \"{}\"", rule.comment));
    }

    out.push('\n');
}

fn render_port_spec(spec: &PortSpec, out: &mut String) {
    match spec {
        PortSpec::Single(port) => out.push_str(&port.to_string()),
        PortSpec::Multiple(ports) => {
            out.push('{');
            for (i, port) in ports.iter().enumerate() {
                if i > 0 {
                    out.push_str(", ");
                }
                out.push_str(&port.to_string());
            }
            out.push('}');
        }
        PortSpec::Range { start, end } => {
            out.push_str(&format!("{}-{}", start, end));
        }
        PortSpec::Set(name) => {
            out.push_str(name); // @set_name — output as-is
        }
    }
}

fn render_nat_table(config: &Config, out: &mut String) {
    out.push_str("table ip nat {\n");

    // Sets referenced by port forwards
    render_nft_sets(config, out);

    // Port forwarding (prerouting)
    let port_forwards: Vec<_> = config
        .firewall
        .nat
        .port_forward
        .iter()
        .filter(|pf| pf.enabled)
        .collect();

    if !port_forwards.is_empty() {
        out.push_str("    chain prerouting {\n");
        out.push_str("        type nat hook prerouting priority -100;\n");

        for pf in &port_forwards {
            // Build iifname match
            let iifname = if pf.interfaces.len() == 1 {
                format!("iifname \"{}\"", pf.interfaces[0])
            } else {
                format!("iifname {{ {} }}", pf.interfaces.iter().map(|i| format!("\"{}\"", i)).collect::<Vec<_>>().join(", "))
            };

            // Expand tcp+udp into two separate rules
            let protos: Vec<&str> = if pf.proto == "tcp+udp" {
                vec!["tcp", "udp"]
            } else {
                vec![pf.proto.as_str()]
            };

            for proto in &protos {
                // Build target port string (WAN dest port match)
                let mut dport = String::new();
                render_port_spec(&pf.target_port, &mut dport);
                // Build redirect port string (dnat to)
                let mut rport = String::new();
                render_port_spec(&pf.redirect_port, &mut rport);

                // Build match expressions
                let mut matches = vec![iifname.clone()];
                if let Some(ref saddr) = pf.source_address {
                    let expr = if saddr == "@local" {
                        "fib daddr type local".to_string()
                    } else {
                        format!("ip saddr {}", saddr)
                    };
                    matches.push(expr);
                }
                if let Some(ref taddr) = pf.target_address {
                    let expr = if taddr == "@local" {
                        "fib daddr type local".to_string()
                    } else {
                        format!("ip daddr {}", taddr)
                    };
                    matches.push(expr);
                }

                out.push_str(&format!(
                    "        {} {} dport {} dnat to {}:{}\n",
                    matches.join(" "), proto, dport, pf.redirect_address, rport
                ));
            }
        }

        out.push_str("    }\n\n");
    }

    // Masquerade + DNAT reply path (postrouting)
    let has_masq = !config.firewall.nat.masquerade.is_empty();
    let has_pf = !port_forwards.is_empty();

    if has_masq || has_pf {
        out.push_str("    chain postrouting {\n");
        out.push_str("        type nat hook postrouting priority 100;\n");

        // Masquerade DNAT'd traffic only when the target is on a local LAN subnet.
        // After DNAT, the packet is forwarded to the target.  If the target is on
        // the LAN, the server would see the original client IP and reply directly
        // — bypassing the router.  Masquerading rewrites the source to the router's
        // LAN IP so the server always replies through us.  If the target is on a
        // non-LAN subnet, the packet routes normally and no NAT is needed.
        let lan_cidr = config
            .interfaces
            .lan()
            .and_then(|lan| lan.static_config.as_ref())
            .map(|c| c.address.as_str());

        for pf in &port_forwards {
            let needs_masq = lan_cidr
                .map(|cidr| is_ip_in_cidr(&pf.redirect_address, cidr))
                .unwrap_or(false);
            if needs_masq {
                let protos: Vec<&str> = if pf.proto == "tcp+udp" {
                    vec!["tcp", "udp"]
                } else {
                    vec![pf.proto.as_str()]
                };
                for proto in &protos {
                    let mut rport = String::new();
                    render_port_spec(&pf.redirect_port, &mut rport);
                    out.push_str(&format!(
                        "        ip daddr {} {} dport {} masquerade\n",
                        pf.redirect_address, proto, rport
                    ));
                }
            }
        }

        for masq in &config.firewall.nat.masquerade {
            out.push_str(&format!("        oifname \"{}\" masquerade\n", masq.oif));
        }

        out.push_str("    }\n");
    }

    out.push_str("}\n\n");
}

fn render_blackhole(config: &Config, out: &mut String) {
    out.push_str("table inet blackhole {\n");
    out.push_str("    set blocked {\n");
    out.push_str("        type ipv4_addr\n");
    out.push_str("        flags interval\n");
    out.push_str("        elements = {\n");

    for (i, cidr) in config.firewall.blackhole.iter().enumerate() {
        if i > 0 {
            out.push_str(",\n");
        }
        out.push_str(&format!("            {}", cidr));
    }

    out.push_str("\n        }\n");
    out.push_str("    }\n\n");

    out.push_str("    chain input {\n");
    out.push_str("        type filter hook input priority -5; policy accept;\n");
    out.push_str("        ip saddr @blocked drop\n");
    out.push_str("    }\n\n");

    out.push_str("    chain forward {\n");
    out.push_str("        type filter hook forward priority -5; policy accept;\n");
    out.push_str("        ip saddr @blocked drop\n");
    out.push_str("        ip daddr @blocked drop\n");
    out.push_str("    }\n");

    out.push_str("}\n");
}

/// Check if an IPv4 address falls within a CIDR range (e.g. "192.168.1.100", "192.168.1.0/24").
fn is_ip_in_cidr(ip: &str, cidr: &str) -> bool {
    let ip_parts: Vec<u8> = match ip.split('.').map(|p| p.parse::<u8>()).collect() {
        Ok(v) => v,
        Err(_) => return false,
    };
    if ip_parts.len() != 4 {
        return false;
    }
    let ip_u32 = ((ip_parts[0] as u32) << 24)
        | ((ip_parts[1] as u32) << 16)
        | ((ip_parts[2] as u32) << 8)
        | (ip_parts[3] as u32);

    let (net_str, prefix_len) = if let Some((net, prefix)) = cidr.split_once('/') {
        (net, prefix.parse::<u32>().unwrap_or(32))
    } else {
        (cidr, 32)
    };

    let net_parts: Vec<u8> = match net_str.split('.').map(|p| p.parse::<u8>()).collect() {
        Ok(v) => v,
        Err(_) => return false,
    };
    if net_parts.len() != 4 {
        return false;
    }
    let net_u32 = ((net_parts[0] as u32) << 24)
        | ((net_parts[1] as u32) << 16)
        | ((net_parts[2] as u32) << 8)
        | (net_parts[3] as u32);

    let mask = if prefix_len == 0 {
        0
    } else {
        !0u32 << (32 - prefix_len)
    };

    (ip_u32 & mask) == (net_u32 & mask)
}

fn needs_nat(config: &Config) -> bool {
    !config.firewall.nat.masquerade.is_empty()
        || config
            .firewall
            .nat
            .port_forward
            .iter()
            .any(|pf| pf.enabled)
}

fn has_tproxy_rules(config: &Config) -> bool {
    config
        .firewall
        .rules
        .input
        .iter()
        .chain(config.firewall.rules.forward.iter())
        .any(|r| r.enabled && r.action == Action::Tproxy)
}

fn render_tproxy_table(config: &Config, out: &mut String) {
    let tproxy_rules: Vec<_> = config
        .firewall
        .rules
        .input
        .iter()
        .chain(config.firewall.rules.forward.iter())
        .filter(|r| r.enabled && r.action == Action::Tproxy)
        .collect();

    if tproxy_rules.is_empty() {
        return;
    }

    out.push_str("table inet mangle {\n");
    out.push_str("    chain prerouting {\n");
    out.push_str("        type filter hook prerouting priority mangle; policy accept;\n");

    for rule in &tproxy_rules {
        out.push_str("        ");
        // Ingress interface
        if !rule.interfaces.is_empty() {
            if rule.interfaces.len() == 1 {
                out.push_str(&format!("iifname \"{}\" ", rule.interfaces[0]));
            } else {
                out.push_str("iifname { ");
                for (i, iface) in rule.interfaces.iter().enumerate() {
                    if i > 0 { out.push_str(", "); }
                    out.push_str(&format!("\"{}\"", iface));
                }
                out.push_str(" } ");
            }
        }
        // Protocol context (must come before dport/sport, required for tproxy)
        if let Some(proto) = &rule.proto {
            out.push_str(&format!("meta l4proto {} ", proto));
        } else if rule.dport.is_some() || rule.sport.is_some() || rule.action == Action::Tproxy {
            out.push_str("meta l4proto tcp ");
        }
        // Address matches
        if let Some(saddr) = &rule.saddr {
            out.push_str(&format!("ip saddr {} ", saddr));
        }
        if let Some(daddr) = &rule.daddr {
            out.push_str(&format!("ip daddr {} ", daddr));
        }
        // Port matches (use protocol prefix for inet table compatibility)
        let proto_prefix = rule.proto.as_deref().unwrap_or("tcp");
        if let Some(dport) = &rule.dport {
            out.push_str(&format!("{} dport ", proto_prefix));
            render_port_spec(dport, out);
            out.push(' ');
        }
        if let Some(sport) = &rule.sport {
            out.push_str(&format!("{} sport ", proto_prefix));
            render_port_spec(sport, out);
            out.push(' ');
        }
        // Counter
        if rule.log {
            // log already includes counter
        } else if rule.counter {
            out.push_str("counter ");
        }
        // mark + tproxy
        let mark = rule.mark.unwrap_or(1);
        let port = rule.tproxy_port.unwrap_or(0);
        out.push_str(&format!("meta mark set {} tproxy ip to :{} accept", mark, port));
        // Inline comment for stats matching
        if !rule.comment.is_empty() {
            out.push_str(&format!(" comment \"{}\"", rule.comment));
        }
        out.push('\n');
    }

    out.push_str("    }\n");
    out.push_str("}\n\n");
}

