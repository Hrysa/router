    #[test]
    fn quotes_and_backslashes_in_credentials_are_escaped() {
        let config = config_with_wan_pppoe(PppoeConfig {
            username: "user\"name".into(),
            password: "pass\\word\"".into(),
            ..Default::default()
        });
        let peers = render(&config).unwrap();
        let secrets = render_chap_secrets(&config).unwrap();
        assert!(peers.contains("user \"user\\\"name\""));
        assert!(peers.contains("password \"pass\\\\word\\\"\""));
        assert!(secrets.contains("\"user\\\"name\" * \"pass\\\\word\\\"\""));
    }

