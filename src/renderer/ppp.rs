use crate::config::schema::*;
use anyhow::Result;

/// Render /etc/ppp/peers/isp from config.
pub fn render(config: &Config) -> Result<String> {
    let wan = match config
        .interfaces
        .items
        .iter()
        .find(|interface| interface.method == InterfaceMethod::Pppoe)
    {
        Some(w) => w,
        None => return Ok("# PPPoE not configured\n".into()),
    };

    let pppoe = match &wan.pppoe {
        Some(p) => p,
        None => return Ok("# PPPoE config missing\n".into()),
    };

    let mut out = String::with_capacity(1024);

    out.push_str("# AUTO-GENERATED by routerd — DO NOT EDIT MANUALLY\n\n");
    out.push_str("plugin pppoe.so\n");
    out.push_str(&format!("{}\n", wan.name));
    out.push_str("ifname ppp0\n");
    out.push_str(&format!("user \"{}\"\n", escape_quoted(&pppoe.username)));
    out.push_str(&format!(
        "password \"{}\"\n",
        escape_quoted(&pppoe.password)
    ));
    out.push_str(&format!("mtu {}\n", pppoe.mtu));
    out.push_str(&format!("mru {}\n", pppoe.mtu));

    out.push_str("defaultroute\n");
    out.push_str("usepeerdns\n");
    out.push_str("noauth\n");
    out.push_str("noipdefault\n");
    out.push_str("nodetach\n");
    out.push_str("holdoff 5\n");

    // Keepalive
    if pppoe.keepalive_interval > 0 {
        out.push_str(&format!("lcp-echo-interval {}\n", pppoe.keepalive_interval));
        out.push_str(&format!("lcp-echo-failure {}\n", pppoe.keepalive_failure));
    }

    out.push_str("persist\n");
    out.push_str("maxfail 0\n");
    out.push_str("connect /bin/true\n");
    out.push_str("noaccomp\n");
    out.push_str("nodeflate\n");
    out.push_str("novj\n");
    out.push_str("novjccomp\n");

    Ok(out)
}

/// Render /etc/ppp/chap-secrets from config.
pub fn render_chap_secrets(config: &Config) -> Result<String> {
    let wan = match config
        .interfaces
        .items
        .iter()
        .find(|interface| interface.method == InterfaceMethod::Pppoe)
    {
        Some(w) => w,
        None => return Ok("# PPPoE not configured\n".into()),
    };

    let pppoe = match &wan.pppoe {
        Some(p) => p,
        None => return Ok("# PPPoE config missing\n".into()),
    };

    let mut out = String::new();
    out.push_str("# AUTO-GENERATED by routerd — DO NOT EDIT MANUALLY\n");
    out.push_str(&format!(
        "\"{}\" * \"{}\"\n",
        escape_quoted(&pppoe.username),
        escape_quoted(&pppoe.password)
    ));

    Ok(out)
}

fn escape_quoted(value: &str) -> String {
    value.replace('\\', "\\\\").replace('"', "\\\"")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn quotes_and_backslashes_in_credentials_are_escaped() {
        let config = config_with_wan_pppoe(PppoeConfig {
            username: "user\"name".into(),
            password: "pass\\word\"".into(),
            ..Default::default()
        });
        let peers = render(&config).unwrap();
        let secrets = render_chap_secrets(&config).unwrap();
        assert!(peers.contains("user \"user\\\"name\""));
        assert!(peers.contains("password \"pass\\\\word\\\"\""));
        assert!(secrets.contains("\"user\\\"name\" * \"pass\\\\word\\\"\""));
    }

    fn config_with_wan_pppoe(pppoe: PppoeConfig) -> Config {
        Config {
            interfaces: Interfaces {
                items: vec![InterfaceConfig {
                    name: "eth0".into(),
                    label: "WAN".into(),
                    method: InterfaceMethod::Pppoe,
                    pppoe: Some(pppoe),
                    ..Default::default()
                }],
            },
            ..Config::default()
        }
    }

    #[test]
    fn selects_pppoe_even_when_static_wan_is_first() {
        let mut config = config_with_wan_pppoe(PppoeConfig {
            username: "subscriber".into(),
            password: "secret".into(),
            ..Default::default()
        });
        config.interfaces.items.insert(
            0,
            InterfaceConfig {
                name: "static-wan".into(),
                static_config: Some(StaticConfig {
                    address: "203.0.113.2/29".into(),
                    gateway: "203.0.113.1".into(),
                    dns: vec![],
                }),
                ..Default::default()
            },
        );
        let peers = render(&config).unwrap();
        assert!(peers.contains("ifname ppp0"));
        assert!(peers.contains("user \"subscriber\""));
        assert!(render_chap_secrets(&config).unwrap().contains("subscriber"));
    }

    #[test]
    fn test_render_pppoe() {
        let config = config_with_wan_pppoe(PppoeConfig {
            username: "user@isp".into(),
            password: "secret123".into(),
            mtu: 1492,
            mss_clamp: true,
            keepalive_interval: 10,
            keepalive_failure: 3,
        });

        let output = render(&config).unwrap();
        assert!(output.contains("plugin pppoe.so"));
        assert!(output.contains("user \"user@isp\""));
        assert!(output.contains("password \"secret123\""));
        assert!(output.contains("mtu 1492"));
        assert!(output.contains("mru 1492"));
        assert!(!output.contains("mssfix"));
        assert!(!output.contains("clamp-mss-to-pmtu"));
        assert!(output.contains("lcp-echo-interval 10"));
        assert!(output.contains("lcp-echo-failure 3"));
        assert!(output.contains("defaultroute"));
        assert!(output.contains("usepeerdns"));
        assert!(output.contains("persist"));
    }

    #[test]
    fn test_render_not_pppoe() {
        let config = Config {
            interfaces: Interfaces {
                items: vec![InterfaceConfig {
                    name: "eth0".into(),
                    method: InterfaceMethod::Dhcp,
                    ..Default::default()
                }],
            },
            ..Config::default()
        };
        let output = render(&config).unwrap();
        assert!(output.contains("not configured"));
    }

    #[test]
    fn test_render_chap_secrets() {
        let config = config_with_wan_pppoe(PppoeConfig {
            username: "user@isp".into(),
            password: "secret123".into(),
            ..Default::default()
        });

        let output = render_chap_secrets(&config).unwrap();
        assert!(output.contains("\"user@isp\" * \"secret123\""));
    }
}
