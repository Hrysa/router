use crate::config::schema::*;
use anyhow::Result;

/// Render /etc/ppp/peers/isp from config.
pub fn render(config: &Config) -> Result<String> {
    let wan = match config.interfaces.wan() {
        Some(w) => w,
        None => return Ok("# No WAN interface configured\n".into()),
    };

    if wan.method != InterfaceMethod::Pppoe {
        return Ok("# PPPoE not configured\n".into());
    }

    let pppoe = match &wan.pppoe {
        Some(p) => p,
        None => return Ok("# PPPoE config missing\n".into()),
    };

    let mut out = String::with_capacity(1024);

    out.push_str("# AUTO-GENERATED by routerd — DO NOT EDIT MANUALLY\n\n");
    out.push_str(&format!("plugin pppoe.so\n"));
    out.push_str(&format!("{}\n", wan.name));
    out.push_str(&format!("user \"{}\"\n", pppoe.username));
    out.push_str(&format!("password \"{}\"\n", pppoe.password));
    out.push_str(&format!("mtu {}\n", pppoe.mtu));
    out.push_str(&format!("mru {}\n", pppoe.mtu));

    if pppoe.mss_clamp {
        let mss = pppoe.mtu.saturating_sub(40);
        out.push_str(&format!("mssfix {}\n", mss));
        out.push_str(&format!("clamp-mss-to-pmtu\n"));
    }

    out.push_str("defaultroute\n");
    out.push_str("usepeerdns\n");
    out.push_str("noauth\n");
    out.push_str("noipdefault\n");
    out.push_str("nodetach\n");
    out.push_str("holdoff 5\n");

    // Keepalive
    if pppoe.keepalive_interval > 0 {
        out.push_str(&format!(
            "lcp-echo-interval {}\n",
            pppoe.keepalive_interval
        ));
        out.push_str(&format!(
            "lcp-echo-failure {}\n",
            pppoe.keepalive_failure
        ));
    }

    out.push_str("persist\n");
    out.push_str("maxfail 0\n");
    out.push_str("connect /bin/true\n");
    out.push_str("noaccomp\n");
    out.push_str("nodeflate\n");
    out.push_str("novj\n");
    out.push_str("novjccomp\n");

    Ok(out)
}

/// Render /etc/ppp/chap-secrets from config.
pub fn render_chap_secrets(config: &Config) -> Result<String> {
    let wan = match config.interfaces.wan() {
        Some(w) => w,
        None => return Ok("# No WAN interface configured\n".into()),
    };

    if wan.method != InterfaceMethod::Pppoe {
        return Ok("# PPPoE not configured\n".into());
    }

    let pppoe = match &wan.pppoe {
        Some(p) => p,
        None => return Ok("# PPPoE config missing\n".into()),
    };

    let mut out = String::new();
    out.push_str("# AUTO-GENERATED by routerd — DO NOT EDIT MANUALLY\n");
    out.push_str(&format!(
        "\"{}\" * \"{}\"\n",
        pppoe.username, pppoe.password
    ));

    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn config_with_wan_pppoe(pppoe: PppoeConfig) -> Config {
        Config {
            interfaces: Interfaces {
                items: vec![InterfaceConfig {
                    name: "eth0".into(),
                    label: "WAN".into(),
                    method: InterfaceMethod::Pppoe,
                    pppoe: Some(pppoe),
                    ..Default::default()
                }],
            },
            ..Config::default()
        }
    }

    #[test]
    fn test_render_pppoe() {
        let config = config_with_wan_pppoe(PppoeConfig {
            username: "user@isp".into(),
            password: "secret123".into(),
            mtu: 1492,
            mss_clamp: true,
            keepalive_interval: 10,
            keepalive_failure: 3,
        });

        let output = render(&config).unwrap();
        assert!(output.contains("plugin pppoe.so"));
        assert!(output.contains("user \"user@isp\""));
        assert!(output.contains("password \"secret123\""));
        assert!(output.contains("mtu 1492"));
        assert!(output.contains("mru 1492"));
        assert!(output.contains("mssfix 1452"));
        assert!(output.contains("lcp-echo-interval 10"));
        assert!(output.contains("lcp-echo-failure 3"));
        assert!(output.contains("defaultroute"));
        assert!(output.contains("usepeerdns"));
        assert!(output.contains("persist"));
    }

    #[test]
    fn test_render_not_pppoe() {
        let config = Config {
            interfaces: Interfaces {
                items: vec![InterfaceConfig {
                    name: "eth0".into(),
                    method: InterfaceMethod::Dhcp,
                    ..Default::default()
                }],
            },
            ..Config::default()
        };
        let output = render(&config).unwrap();
        assert!(output.contains("not configured"));
    }

    #[test]
    fn test_render_chap_secrets() {
        let config = config_with_wan_pppoe(PppoeConfig {
            username: "user@isp".into(),
            password: "secret123".into(),
            ..Default::default()
        });

        let output = render_chap_secrets(&config).unwrap();
        assert!(output.contains("\"user@isp\" * \"secret123\""));
    }
}
