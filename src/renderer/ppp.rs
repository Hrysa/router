use crate::config::schema::*;
use anyhow::Result;

/// Render /etc/ppp/peers/isp from config.
pub fn render(config: &Config) -> Result<String> {
    let wan = match config
        .interfaces
        .items
        .iter()
        .find(|interface| interface.method == InterfaceMethod::Pppoe)
    {
        Some(w) => w,
        None => return Ok("# PPPoE not configured\n".into()),
    };

    let pppoe = match &wan.pppoe {
        Some(p) => p,
        None => return Ok("# PPPoE config missing\n".into()),
    };

    let mut out = String::with_capacity(1024);

    out.push_str("# AUTO-GENERATED by routerd — DO NOT EDIT MANUALLY\n\n");
    out.push_str("plugin pppoe.so\n");
    out.push_str(&format!("{}\n", wan.name));
    out.push_str("ifname ppp0\n");
    out.push_str("ipparam routerd-isp\n");
    out.push_str(&format!("user \"{}\"\n", escape_quoted(&pppoe.username)));
    out.push_str(&format!(
        "password \"{}\"\n",
        escape_quoted(&pppoe.password)
    ));
    out.push_str(&format!("mtu {}\n", pppoe.mtu));
    out.push_str(&format!("mru {}\n", pppoe.mtu));

    out.push_str("defaultroute\n");
    out.push_str("usepeerdns\n");
    out.push_str("noauth\n");
    out.push_str("noipdefault\n");
    out.push_str("nodetach\n");
    out.push_str("holdoff 5\n");

    // Keepalive
    if pppoe.keepalive_interval > 0 {
        out.push_str(&format!("lcp-echo-interval {}\n", pppoe.keepalive_interval));
        out.push_str(&format!("lcp-echo-failure {}\n", pppoe.keepalive_failure));
    }

    out.push_str("persist\n");
    out.push_str("maxfail 0\n");
    out.push_str("noaccomp\n");
    out.push_str("nodeflate\n");
    out.push_str("novj\n");
    out.push_str("novjccomp\n");

    Ok(out)
}

/// Render /etc/ppp/chap-secrets from config.
pub fn render_chap_secrets(config: &Config) -> Result<String> {
    let wan = match config
        .interfaces
        .items
        .iter()
        .find(|interface| interface.method == InterfaceMethod::Pppoe)
    {
        Some(w) => w,
        None => return Ok("# PPPoE not configured\n".into()),
    };

    let pppoe = match &wan.pppoe {
        Some(p) => p,
        None => return Ok("# PPPoE config missing\n".into()),
    };

    let mut out = String::new();
    out.push_str("# AUTO-GENERATED by routerd — DO NOT EDIT MANUALLY\n");
    out.push_str(&format!(
        "\"{}\" * \"{}\"\n",
        escape_quoted(&pppoe.username),
        escape_quoted(&pppoe.password)
    ));

    Ok(out)
}

/// Run only after IPCP installs the IPv4 address. pppd address setup can
/// remove a route installed earlier by networkd; its ip-up dispatcher reruns
/// this hook after every reconnect. Other PPP connections are left untouched.
pub fn render_ip_up(config: &Config) -> Result<String> {
    render_ip_up_command(config, "ip")
}

fn render_ip_up_command(config: &Config, command: &str) -> Result<String> {
    let routes = crate::config::routing::wan_return_routes(config)?;
    let route = routes
        .iter()
        .find(|route| matches!(route.kind, crate::config::routing::WanRouteKind::Pppoe));
    let Some(route) = route else {
        return Ok(
            "#!/bin/sh\n# Managed by routerd: PPP WAN return routing disabled.\nexit 0\n".into(),
        );
    };
    let command = command.replace('\'', "'\"'\"'");
    Ok(format!(
        "#!/bin/sh\n# Managed by routerd: restore the dedicated IPv4 WAN default after IPCP.\nset -eu\n[ \"${{PPP_IFACE:-${{1:-}}}}\" = ppp0 ] || exit 0\n[ \"${{PPP_IPPARAM:-${{6:-}}}}\" = routerd-isp ] || exit 0\nexec '{command}' -4 route replace default dev ppp0 scope link proto static table {}\n",
        route.table
    ))
}

fn escape_quoted(value: &str) -> String {
    value.replace('\\', "\\\\").replace('"', "\\\"")
}

