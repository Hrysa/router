import { useState } from 'react';
import { AlertTriangle, Code, Save } from 'react-feather';
import { request, write } from '../lib/api';
import { errorMessage } from '../lib/format';
import { useApi, useConfig } from '../lib/queries';
import type { Hooks } from '../lib/types';
import {
  Card,
  Loading,
  PageHeader,
  QueryNotice,
  useSave,
  useUi,
  useUnsaved,
} from '../lib/ui';

export function ConfigEditors({ mode }: { mode: 'hooks' | 'singbox' }) {
  return mode === 'singbox' ? <Singbox /> : <StartupHooks />;
}
function Singbox() {
  const query = useApi<{ raw: string }>('/singbox/config');
  return (
    <>
      <PageHeader
        title="sing-box"
        description="Your proxy configuration, exactly as you wrote it."
      />
      <div className="info-banner">
        <Code size={20} />
        <p>
          This is a user-managed JSONC file, not generated by routerd. Comments
          are preserved. Save validates the file when sing-box is available;
          Apply attempts to restart sing-box.
        </p>
      </div>
      <QueryNotice query={query} />
      {query.isPending ? (
        <Loading />
      ) : (
        query.data && <RawEditor initial={query.data.raw} />
      )}
    </>
  );
}
function RawEditor({ initial }: { initial: string }) {
  const [value, setValue] = useState(initial);
  const [baseline, setBaseline] = useState(initial);
  const [error, setError] = useState('');
  const dirty = value !== baseline;
  const ui = useUi();
  useUnsaved(dirty);
  const save = useSave((body: string) =>
    request('/singbox/config', { method: 'PUT', body, raw: true }),
  );
  return (
    <Card
      title="config.jsonc"
      subtitle="/etc/sing-box/config.jsonc"
      actions={<BadgeUnsaved dirty={dirty} />}
    >
      <form
        onSubmit={async (event) => {
          event.preventDefault();
          if (
            !(await ui.confirm({
              title: 'Save sing-box configuration?',
              message:
                'This overwrites the user-managed file. The running process is unchanged until Apply or a service restart.',
              label: 'Save configuration',
            }))
          )
            return;
          setError('');
          try {
            await save.mutateAsync(value);
            setBaseline(value);
          } catch (failure) {
            setError(errorMessage(failure));
          }
        }}
      >
        <textarea
          className="code-editor"
          aria-label="sing-box JSONC configuration"
          spellCheck={false}
          value={value}
          onChange={(event) => setValue(event.target.value)}
          disabled={save.isPending}
        />
        {error && (
          <p className="form-error editor-error" role="alert">
            {error}
          </p>
        )}
        <div className="editor-footer">
          <span>JSON with comments · {value.split('\n').length} lines</span>
          <button className="primary" disabled={!dirty || save.isPending}>
            <Save size={16} />
            {save.isPending ? 'Saving…' : 'Save configuration'}
          </button>
        </div>
      </form>
    </Card>
  );
}
function StartupHooks() {
  const config = useConfig();
  return (
    <>
      <PageHeader
        title="Startup hooks"
        description="A little automation, at the right moment."
      />
      <div className="warning-banner">
        <AlertTriangle size={21} />
        <p>
          These scripts run as the routerd user, usually root, at normal daemon
          startup. They do not run on every API Apply. Only use trusted shell
          commands.
        </p>
      </div>
      <QueryNotice query={config} />
      {config.isPending ? (
        <Loading />
      ) : (
        config.data && (
          <HooksEditor
            initial={config.data.hooks ?? { before_start: '', after_start: '' }}
          />
        )
      )}
    </>
  );
}
function HooksEditor({ initial }: { initial: Hooks }) {
  const [hooks, setHooks] = useState(initial);
  const [baseline, setBaseline] = useState(initial);
  const dirty = JSON.stringify(hooks) !== JSON.stringify(baseline);
  useUnsaved(dirty);
  const ui = useUi();
  const save = useSave(
    (body: Hooks) => write('/config/hooks', body),
    'Hooks saved for the next normal daemon startup.',
    false,
  );
  return (
    <form
      onSubmit={async (event) => {
        event.preventDefault();
        if (
          !(await ui.confirm({
            title: 'Save startup hooks?',
            message:
              'These shell commands execute with routerd privileges on the next normal startup, not on API Apply.',
            label: 'Save hooks',
            dangerous: true,
          }))
        )
          return;
        try {
          await save.mutateAsync(hooks);
          setBaseline(hooks);
        } catch {
          return;
        }
      }}
    >
      {(['before_start', 'after_start'] as const).map((name) => (
        <Card
          key={name}
          title={name === 'before_start' ? 'Before startup' : 'After startup'}
          subtitle={
            name === 'before_start'
              ? 'Runs before the normal startup apply pipeline.'
              : 'Runs after the normal startup apply pipeline.'
          }
        >
          <textarea
            className="code-editor hook-editor"
            aria-label={
              name === 'before_start'
                ? 'Before startup script'
                : 'After startup script'
            }
            spellCheck={false}
            placeholder="#!/bin/sh"
            value={hooks[name]}
            disabled={save.isPending}
            onChange={(event) =>
              setHooks((current) => ({
                ...current,
                [name]: event.target.value,
              }))
            }
          />
        </Card>
      ))}
      <div className="editor-save-row">
        <BadgeUnsaved dirty={dirty} />
        <button className="primary" disabled={!dirty || save.isPending}>
          <Save size={16} />
          {save.isPending ? 'Saving…' : 'Save hooks'}
        </button>
      </div>
    </form>
  );
}
function BadgeUnsaved({ dirty }: { dirty: boolean }) {
  return (
    <span className={dirty ? 'unsaved-label' : 'subtle'}>
      {dirty ? 'Unsaved edits' : 'No unsaved edits'}
    </span>
  );
}
